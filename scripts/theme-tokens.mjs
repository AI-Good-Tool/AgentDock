// Replace hard-coded colors in reused stylesheets with CSS variables and
// generate a dark palette by lightness inversion (hue/saturation kept).
// Usage: node scripts/theme-tokens.mjs <file.css|file.vue>... -> src/theme-tokens.css
import { readFileSync, writeFileSync } from 'node:fs';

const files = process.argv.slice(2);
const colors = new Map();
const hex = /#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b/g;
const norm = (h) => (h.length === 4 ? '#' + [...h.slice(1)].map((c) => c + c).join('') : h).toLowerCase();
function toHsl(h) {
  const n = parseInt(h.slice(1), 16), r = (n >> 16) / 255, g = ((n >> 8) & 255) / 255, b = (n & 255) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  let s = 0, hue = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    hue = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    hue /= 6;
  }
  return [hue * 360, s, l];
}
function dark(h) {
  const [hue, s, l] = toHsl(h);
  let nl;
  if (l > 0.82) nl = 0.09 + (1 - l) * 0.55; // surfaces and tints -> dark surfaces
  else if (l < 0.42) nl = 0.93 - l * 0.45; // text -> light text
  else nl = Math.min(0.72, l + 0.08); // accents stay recognizable
  const ns = l > 0.82 ? Math.min(s, 0.35) : s;
  return `hsl(${hue.toFixed(0)} ${(ns * 100).toFixed(0)}% ${(nl * 100).toFixed(1)}%)`;
}
function inStyle(file, text) {
  if (!file.endsWith('.vue')) return [[0, text.length]];
  const ranges = [];
  const re = /<style[^>]*>([\s\S]*?)<\/style>/g;
  let m;
  while ((m = re.exec(text))) ranges.push([m.index, m.index + m[0].length]);
  return ranges;
}
for (const file of files) {
  const text = readFileSync(file, 'utf8');
  const ranges = inStyle(file, text);
  let out = '', last = 0;
  for (const [a, b] of ranges) {
    out += text.slice(last, a);
    out += text.slice(a, b).replace(hex, (m) => {
      const c = norm(m);
      const name = `--c-${c.slice(1)}`;
      colors.set(name, c);
      return `var(${name})`;
    });
    last = b;
  }
  out += text.slice(last);
  writeFileSync(file, out);
}
const light = [...colors].map(([n, c]) => `  ${n}: ${c};`).join('\n');
const darkVars = [...colors].map(([n, c]) => `  ${n}: ${dark(c)};`).join('\n');
writeFileSync(
  'src/theme-tokens.css',
  `/* Generated by scripts/theme-tokens.mjs */\n:root {\n${light}\n}\n:root[data-theme='dark'] {\n${darkVars}\n}\n`,
);
console.log(`${colors.size} colors tokenized`);
